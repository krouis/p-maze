/**
 * Returns the theme for a level. If highContrast is enabled, returns the High Contrast theme.
 */
export function getThemeForLevel(level: number, highContrast: boolean): LevelTheme {
  if (highContrast) {
    return HIGH_CONTRAST_THEME;
  }
  const index = (level - 1) % CURATED_THEMES.length;
  return CURATED_THEMES[index];
}
